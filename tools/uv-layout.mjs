// Exports the UV layout and the mesh of the clothing page to tools/uv-layout.json.
//
// The painter uses the triangles to know, for every atlas pixel, where it sits
// on the body. That is what lets an outfit be designed in body space ("the
// skirt is below the waist") instead of guessing at atlas coordinates.
//
// Run it while the app is open:
//   node tools/uv-layout.mjs
const PORT = 9222;
const fs = await import("node:fs");
const path = await import("node:path");

const list = await (await fetch(`http://127.0.0.1:${PORT}/json/list`)).json();
const page = list.find((t) => t.type === "page");
if (!page) {
  console.error("no webview page found - is the app running?");
  process.exit(1);
}
const ws = new WebSocket(page.webSocketDebuggerUrl);
const pending = new Map();
let id = 0;
ws.addEventListener("message", (e) => {
  const msg = JSON.parse(e.data);
  const cb = pending.get(msg.id);
  if (cb) {
    pending.delete(msg.id);
    cb(msg);
  }
});
await new Promise((r) => ws.addEventListener("open", r));
const send = (method, params) =>
  new Promise((r) => {
    const myId = ++id;
    pending.set(myId, r);
    ws.send(JSON.stringify({ id: myId, method, params }));
  });

const expr = `
(() => {
  const model = window.ei.character.model;
  const core = model.internalModel.coreModel;
  const src = core._model.drawables;
  const partIds = core._partIds.slice();
  const childOf = core._partChildDrawables.map((a) => (a ? a.slice() : []));
  const drawables = [];
  for (let i = 0; i < src.count; i++) {
    const n = src.vertexCounts[i];
    if (!n) continue;
    let part = -1;
    for (let p = 0; p < childOf.length; p++) if (childOf[p].includes(i)) { part = p; break; }
    const pos = Array.from(src.vertexPositions[i]).slice(0, n * 2);
    const uv = Array.from(src.vertexUvs[i]).slice(0, n * 2);
    const indices = Array.from(src.indices[i]).slice(0, src.indexCounts[i]);
    let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
    let u0 = Infinity, v0 = Infinity, u1 = -Infinity, v1 = -Infinity;
    for (let k = 0; k < n; k++) {
      const x = pos[k * 2], y = pos[k * 2 + 1];
      if (x < x0) x0 = x; if (x > x1) x1 = x;
      if (y < y0) y0 = y; if (y > y1) y1 = y;
      const u = uv[k * 2], v = uv[k * 2 + 1];
      if (u < u0) u0 = u; if (u > u1) u1 = u;
      if (v < v0) v0 = v; if (v > v1) v1 = v;
    }
    drawables.push({
      index: i,
      name: src.ids[i],
      texture: src.textureIndices[i],
      part: part >= 0 ? partIds[part] : null,
      opacity: src.opacities[i],
      positions: pos.map((v) => Math.round(v * 1e6) / 1e6),
      uvs: uv.map((v) => Math.round(v * 1e6) / 1e6),
      indices,
      uvBox: { u0, v0, u1, v1 },
      bodyBox: { x0, y0, x1, y1 },
    });
  }
  return {
    source: model.textures[0].baseTexture.resource.url,
    canvas: { width: model.internalModel.originalWidth, height: model.internalModel.originalHeight },
    drawables,
  };
})()`;

const out = await send("Runtime.evaluate", { expression: expr, returnByValue: true });
if (out.result?.exceptionDetails) {
  console.error(JSON.stringify(out.result.exceptionDetails, null, 2));
  process.exit(1);
}
const layout = out.result.result.value;
layout.note =
  "Generated by tools/uv-layout.mjs from the live model. positions are model units (y up), uvs are 0..1 of the texture page, indices are the triangle list of every drawable.";
const file = path.resolve("E:/Ei Model/tools/uv-layout.json");
fs.writeFileSync(file, JSON.stringify(layout, null, 2) + "\n");
const kb = (fs.statSync(file).size / 1024).toFixed(0);
console.log(`wrote ${file} (${kb} kB, ${layout.drawables.length} drawables)`);
const clothes = layout.drawables.filter((d) => d.texture === 1 && d.part !== "Part01HairBack001");
console.log(`clothing page drawables: ${clothes.length}, triangles: ${clothes.reduce((s, d) => s + d.indices.length / 3, 0)}`);
ws.close();
